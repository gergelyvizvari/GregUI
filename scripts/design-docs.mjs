// Writes docs/styles/<preset>.md from the built tokens. `--check` fails when a file is stale.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  createTheme,
  designMarkdown,
  featuredPresets,
  presetInfo,
  recommendedPalettes,
} from '../packages/tokens/dist/index.js';
const check = process.argv.includes('--check');
const dir = join(process.cwd(), 'docs', 'styles');
const files = {
  'README.md': [
    '# Style guides',
    '',
    'Each file is a DESIGN.md for one gregUI preset with its recommended palette. Point an AI coding tool at the file for the style you use, or export one for your own theme from the workbench (Theme studio, Export DESIGN.md).',
    '',
    'These files are generated by `npm run docs:styles` from `@gregui/tokens`. Do not edit them by hand.',
    '',
    ...featuredPresets.map(
      (preset) => `- [${presetInfo[preset].name}](${preset}.md): ${presetInfo[preset].description}`,
    ),
    '',
  ].join('\n'),
};
for (const preset of featuredPresets)
  files[`${preset}.md`] = designMarkdown(createTheme(preset, 'light', recommendedPalettes[preset]));
mkdirSync(dir, { recursive: true });
const stale = [];
for (const [name, content] of Object.entries(files)) {
  const path = join(dir, name);
  let current = null;
  try {
    current = readFileSync(path, 'utf8');
  } catch {}
  if (current === content) continue;
  if (check) stale.push(name);
  else writeFileSync(path, content);
}
if (stale.length) {
  console.error(`Style guides are out of date (${stale.join(', ')}). Run npm run docs:styles.`);
  process.exit(1);
}
