const catalogs: Record<string, Messages> = { en: english, hu: hungarian };
/** Built-in package messages for a BCP 47 locale's language, falling back to English. */
export function messagesFor(locale: string): Messages {
  return catalogs[locale.split(/[-_]/)[0]!.toLowerCase()] ?? english;
}
interface LocaleValue {
  locale: string;
  direction: 'ltr' | 'rtl';
  timeZone: string;
  messages: Messages;
}
const LocaleContext = createContext<LocaleValue>({
  locale: 'en-GB',
  direction: 'ltr',
  timeZone: 'UTC',
  messages: english,
});
const noOverrides: Partial<Messages> = {};
export function LocaleProvider({
  locale = 'en-GB',
  direction = 'ltr',
  timeZone = 'UTC',
  messages = noOverrides,
  children,
}: {
  locale?: string;
  direction?: 'ltr' | 'rtl';
  timeZone?: string;
  messages?: Partial<Messages>;
  children: ReactNode;
}) {
  const value = useMemo(
    () => ({ locale, direction, timeZone, messages: { ...messagesFor(locale), ...messages } }),
    [locale, direction, timeZone, messages],
  );
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}
export function useLocale() {
  return useContext(LocaleContext);
}
export function useFormat() {
  const { locale, timeZone } = useLocale();
  return useMemo(
    () => ({
      number: (value: number, options?: Intl.NumberFormatOptions) =>
        new Intl.NumberFormat(locale, options).format(value),
      date: (value: Date | number, options?: Intl.DateTimeFormatOptions) =>
        new Intl.DateTimeFormat(locale, { timeZone, ...options }).format(value),
      plural: (value: number) => new Intl.PluralRules(locale).select(value),
    }),
    [locale, timeZone],
  );
}
